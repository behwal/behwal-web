export const getServerSideProps: GetServerSideProps<Props> = async () => {
  const endpoint = process.env.COSMOS_DB_ENDPOINT;
  const key = process.env.COSMOS_DB_KEY;
  const databaseName = process.env.COSMOS_DB_DATABASE;
  const containerName = process.env.COSMOS_DB_CONTAINER;

  const client = new CosmosClient({ endpoint, key });
  const database = client.database(databaseName);
  const container = database.container(containerName);

  const query = "SELECT * FROM c where c.active = true";
  const { resources: data } = await container.items.query(query).fetchAll();

  return {
    props: {
      data,
    },
  };
};